function writeOrCheck(file, obj) {
  const next = JSON.stringify(obj, null, 2) + '\n';
  if (checkMode) {
    const cur = existsSync(file) ? readFileSync(file, 'utf-8') : '';
    if (cur !== next) {
      console.error(`[regen --check] STALE: ${file} differs from generated output. Run: node scripts/regen-workspace-specs.mjs`);
      process.exit(1);
    }
    console.log(`[regen --check] ok: ${file}`);
    return;
  }
  if (!existsSync(OUT_DIR)) mkdirSync(OUT_DIR, { recursive: true });
  writeFileSync(file, next);
  console.log(`[regen] wrote ${file}`);
}

