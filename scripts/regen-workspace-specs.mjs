#!/usr/bin/env node
// Regenerates src/lib/workspace/gatesSpec.json from the LIVE gate manifest
// (`theme-gates.mjs --list`) and pipelineSpec.json from the canonical 18-step
// doctrine. This is the anti-drift audit trail (plan §C8): the dashboard's gate
// list is GENERATED from the toolkit, never hand-typed from memory.
//
// Run:  node scripts/regen-workspace-specs.mjs
// CI:   add `--check` to fail the build if the committed spec is stale.

import { execFileSync } from 'node:child_process';
import { writeFileSync, readFileSync, existsSync, mkdirSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const ROOT = resolve(__dirname, '..');
const OUT_DIR = resolve(ROOT, 'src/lib/workspace');
const GATES_OUT = resolve(OUT_DIR, 'gatesSpec.json');
const PIPELINE_OUT = resolve(OUT_DIR, 'pipelineSpec.json');
const GATES_SCRIPT = resolve(ROOT, 'theme-toolkit/scripts/theme-gates.mjs');

const checkMode = process.argv.includes('--check');

// ── Gates: read `theme-gates.mjs --list-json` → canonical spec ──────────────
// Use the STRUCTURED manifest (not the --list text) so decimal-numbered gates (#0.4/#0.5),
// library-kind gates (#20 cards), and the branded `family` field are all captured.
function buildGatesSpec() {
  let raw;
  try {
    raw = execFileSync('node', [GATES_SCRIPT, '--list-json'], { encoding: 'utf-8' });
  } catch (err) {
    console.error('[regen] failed to run theme-gates.mjs --list-json:', err.message);
    process.exit(2);
  }
  let manifest;
  try { manifest = JSON.parse(raw); } catch (err) {
    console.error('[regen] --list-json did not parse:', err.message); process.exit(2);
  }
  const gates = manifest.map((g) => ({
    number: g.number, stage: g.stage, category: g.category, desc: g.desc, // decimal ok
    name: g.name,
    // (category replaces family)
    kind: g.kind,                      // static | url | library
    script: g.script,
    blocking: true,                    // every gate is a hard block in our doctrine
    reportFile: `${g.name}.json`,      // report stem === gate name (plan §C4)
  }));
  if (gates.length < 10) { console.error('[regen] suspiciously few gates parsed:', gates.length); process.exit(2); }
  return {
    _source: 'GENERATED by scripts/regen-workspace-specs.mjs from `theme-gates.mjs --list-json` — do not hand-edit',
    _generatedFrom: 'theme-toolkit/scripts/theme-gates.mjs',
    count: gates.length,
    gates,
  };
}

