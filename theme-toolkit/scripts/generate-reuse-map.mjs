#!/usr/bin/env node
// generate-reuse-map — derive the mechanical half of section-reuse-map.md, and REFUSE to invent the rest.
//
// WHY THIS EXISTS (GI-2, 2026-07-23). Gate #23 needs `section-reuse-map.md`, but nothing in the toolkit
// could ever produce one, so it is simply never written — cravinbyandy shipped 9 days and 16 custom
// sections without it. Most of the map is derivable from git + the template JSON, which is exactly the
// part a human should not be hand-counting.
//
// WHAT IS DELIBERATELY *NOT* GENERATED — the whole point of this script:
//   · `Custom split: {library: N, scratch: N}` — whether a custom section was built from a component-
//     library blueprint or written from scratch is authorship history. It is not in the repo.
//   · `blueprint: none (checked: …, gap: …)` justifications — the reasoning for going custom.
// Guessing either would let a build pass onyx Audit 7 on invented numbers, which is strictly worse than
// having no map: a fabricated pass is indistinguishable from a real one. So this emits those as TODO
// markers, which makes gate #23 BLOCK (`reuse-map.custom-split-missing`) until a human fills them in.
// A half-authored map must fail loudly, never coast.
//
//   node toolkit/scripts/generate-reuse-map.mjs [--out section-reuse-map.md] [--force]
//
// Counts are FILE-based, not instance-based, because that is what gate #23 cross-checks:
// `custom` must equal the number of sections/*.liquid files ADDED since BASE_REF.
// Env: BASE_REF (default "base"), OUT (default section-reuse-map.md).
// Exit: 0 written · 2 env error (not a git repo / base ref unresolvable / refusing to overwrite).

import fs from 'node:fs'
import path from 'node:path'
import { execFileSync } from 'node:child_process'
import { fileURLToPath } from 'node:url'

const cwd = process.cwd()
const BASE_REF = process.env.BASE_REF || 'base'
const die = (msg) => { console.error(`generate-reuse-map: ${msg}`); process.exit(2) }

// same helper as check-reference-match.mjs — Shopify template JSON is JSONC (/* */ comments),
// so a bare JSON.parse throws on every stock Dawn template.
const stripJsonComments = (s) => s.replace(/\/\*[\s\S]*?\*\//g, '')

function parseArgs(argv) {
  const o = {}
  for (let i = 0; i < argv.length; i += 1) {
    const a = argv[i]
    if (a === '--out') o.out = argv[++i]
    else if (a === '--force') o.force = true
  }
  return o
}

// PURE: given the git facts + the section instances actually referenced, produce file-based counts.
// `used` is a Map<type, {hasSettings:boolean}>. main-* drivers are excluded from the reuse denominator
// per section-reuse-first-protocol.md §Targets ("main-* drivers and header/footer groups are excluded
// … because they are always REUSE") — but ADDED files always count as custom, since gate #23's
// cross-check counts every new section file on disk.
export function deriveCounts({ added, modified, used }) {
  const isMain = (t) => t.startsWith('main-')
  const stockUsed = [...used.keys()].filter(t => !added.has(t) && !modified.has(t) && !isMain(t))
  const configured = stockUsed.filter(t => used.get(t).hasSettings).sort()
  const reused = stockUsed.filter(t => !used.get(t).hasSettings).sort()
  const custom = [...added].sort()
  const extended = [...modified].sort()
  // a custom section file that no template references — dead weight, and invisible to every
  // render-time gate because nothing renders it.
  const unused = custom.filter(t => !used.has(t))
  return { reused, configured, extended, custom, unused }
}

export function renderMap(c, { baseRef = 'base' } = {}) {
  const n = { reused: c.reused.length, configured: c.configured.length, extended: c.extended.length, custom: c.custom.length }
  const total = n.reused + n.configured + n.extended + n.custom
  const share = total ? (((n.reused + n.configured) / total) * 100).toFixed(0) : '0'
  const rows = [
    ...c.reused.map(t => `| ${t} | ${t} | REUSE | stock section, template settings match schema defaults |`),
    ...c.configured.map(t => `| ${t} | ${t} | CONFIGURE | stock section, configured via template settings |`),
    ...c.extended.map(t => `| ${t} | ${t} | EXTEND | stock section modified since \`${baseRef}\` |`),
    ...c.custom.map(t => `| ${t} | ${t} | CUSTOM | section file added since \`${baseRef}\` |`),
  ]
  return `# Section reuse map

<!-- PARTIALLY GENERATED by toolkit/scripts/generate-reuse-map.mjs.
     The counts + rungs below are DERIVED from git and the template JSON — do not hand-edit them;
     re-run the generator instead. The TODO block at the bottom is NOT derivable and must be
     completed by the person who built these sections. Until it is, gate #23 BLOCKS. -->

Counts: {reused: ${n.reused}, configured: ${n.configured}, extended: ${n.extended}, custom: ${n.custom}}

Derived against \`${baseRef}\` · reuse+configure share ${share}%
(On a Dawn base this share is informational only — Dawn is custom-first, see
section-reuse-first-protocol.md §Targets. On Minimog the ≥70% floor applies.)

| Zone | Section | Rung | Evidence |
|---|---|---|---|
${rows.join('\n')}
${c.unused.length ? `
> ⚠️ ${c.unused.length} custom section file(s) are referenced by NO template — dead weight that no
> render-time gate can see: ${c.unused.map(t => `\`${t}.liquid\``).join(', ')}.
> Either wire them into a template or delete them.
` : ''}
## TODO — not derivable, a human must complete this

These two fields encode authorship history that does not exist anywhere in the repo. They are
deliberately left unfilled: a fabricated value here would let the build pass onyx Audit 7 on invented
numbers, which is worse than having no map at all.

1. **Custom split.** For each CUSTOM section decide whether it was built from a component-library
   blueprint (LIBRARY) or written from scratch (SCRATCH), then add the line:
   \`Custom split: {library: N, scratch: N}\`   (library + scratch must equal custom = ${n.custom})
2. **Justify every one.** LIBRARY sections cite the blueprint they came from; SCRATCH sections state
   what was checked first and why nothing fitted:
   \`<section-name>: blueprint: <blueprint-id>@v1\`
   \`<section-name>: blueprint: none (checked: <sections you evaluated>, gap: <what was missing>)\`

Unfilled checklist — delete each line as you add its citation above:
${c.custom.map(t => `- [ ] ${t}`).join('\n')}
`
}

function main() {
  const o = parseArgs(process.argv.slice(2))
  const OUT = o.out || process.env.OUT || 'section-reuse-map.md'
  const outAbs = path.resolve(cwd, OUT)
  if (fs.existsSync(outAbs) && !o.force) {
    die(`${OUT} already exists — refusing to overwrite a hand-authored map. Re-run with --force if you really mean it.`)
  }

  const git = (args) => {
    try { return execFileSync('git', args, { cwd, encoding: 'utf-8' }).trim() } catch { return null }
  }
  if (git(['rev-parse', '--is-inside-work-tree']) !== 'true') die('not a git repository — the reuse map is derived from the diff against the theme base')
  if (git(['rev-parse', '--verify', `${BASE_REF}^{commit}`]) === null) {
    die(`base ref "${BASE_REF}" unresolvable — tag the pulled theme base first (\`git tag ${BASE_REF} <commit>\`). Without it, custom vs stock cannot be told apart.`)
  }

  const names = (filter) => new Set(
    (git(['diff', `--diff-filter=${filter}`, '--name-only', BASE_REF, 'HEAD', '--', 'sections/*.liquid']) || '')
      .split('\n').filter(Boolean).map(f => path.basename(f, '.liquid')),
  )
  const added = names('A')
  const modified = names('M')

  const jsonFiles = []
  for (const dir of ['templates', 'sections']) {
    const abs = path.resolve(cwd, dir)
    if (!fs.existsSync(abs)) continue
    for (const f of fs.readdirSync(abs)) if (f.endsWith('.json')) jsonFiles.push(path.join(dir, f))
  }
  const used = new Map()
  const unparseable = []
  for (const rel of jsonFiles) {
    let j
    try { j = JSON.parse(stripJsonComments(fs.readFileSync(path.resolve(cwd, rel), 'utf-8'))) } catch { unparseable.push(rel); continue }
    for (const v of Object.values(j.sections || {})) {
      const t = (v && v.type) || ''
      if (!t) continue
      const e = used.get(t) || { hasSettings: false }
      if (v.settings && Object.keys(v.settings).length) e.hasSettings = true
      used.set(t, e)
    }
  }

  const counts = deriveCounts({ added, modified, used })
  fs.writeFileSync(outAbs, renderMap(counts, { baseRef: BASE_REF }))

  console.log(`generate-reuse-map: wrote ${OUT}`)
  console.log(`  reused ${counts.reused.length} · configured ${counts.configured.length} · extended ${counts.extended.length} · custom ${counts.custom.length}`)
  if (unparseable.length) console.log(`  ⚠ ${unparseable.length} template(s) could not be parsed and were skipped: ${unparseable.join(', ')}`)
  if (counts.unused.length) console.log(`  ⚠ ${counts.unused.length} custom section(s) referenced by no template: ${counts.unused.join(', ')}`)
  console.log('  INCOMPLETE BY DESIGN: Custom split + blueprint justifications are TODO — gate #23 will BLOCK')
  console.log('  until a human fills them in. That is intentional; do not invent them to make the gate green.')
  process.exit(0)
}

// fileURLToPath, NOT new URL(...).pathname — the latter percent-encodes, so any repo path containing
// a space (e.g. "Boldteq App") never matches argv[1] and main() silently never runs.
if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) main()
