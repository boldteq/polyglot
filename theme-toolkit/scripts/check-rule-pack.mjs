#!/usr/bin/env node
// Gate #43 rule-pack — data-driven enforcement (the scalable substrate). Loads declarative rules
// (team-default bundled with the toolkit + an optional per-store pack) and runs the shared
// rule-engine over the theme. ENFORCING a guideline = appending a JSON line, not coding a gate.
// The team-default pack is grown AUTOMATICALLY by scripts/quality-loop.mjs — a real caught defect
// becomes an enforced rule, so the same mistake can never silently recur on the next build.
//
// Usage: node check-rule-pack.mjs   ·   Env: RULE_PACK_FILE (per-store, docs/brand/rule-pack.json) · REPORT_DIR
// Exit: 0 = pass · 1 = a rule blocked · 2 = malformed pack

import fs from 'node:fs'
import path from 'node:path'
import { execFileSync } from 'node:child_process'
import { fileURLToPath } from 'node:url'
import { writeReport } from './lib/report.mjs'
import { evaluateRules } from './lib/rule-engine.mjs'

const t0 = Date.now()
const cwd = process.cwd()
const HERE = path.dirname(fileURLToPath(import.meta.url)) // fileURLToPath: repo path has a space
const TEAM_DEFAULT = path.join(HERE, '..', 'toolkit-rules', 'team-default.json')
const STORE_PACK = process.env.RULE_PACK_FILE || 'docs/brand/rule-pack.json'
const REPORT_DIR = process.env.REPORT_DIR || 'gate-reports'

function walk(dir, exts, acc = []) {
  const abs = path.resolve(cwd, dir)
  if (!fs.existsSync(abs)) return acc
  for (const e of fs.readdirSync(abs, { withFileTypes: true })) {
    const rel = path.join(dir, e.name)
    if (e.isDirectory()) walk(rel, exts, acc)
    else if (exts.some((x) => e.name.endsWith(x))) acc.push(rel)
  }
  return acc
}
const readFile = (f) => { try { return fs.readFileSync(path.resolve(cwd, f), 'utf-8') } catch { return '' } }
const toEntries = (files) => files.map((f) => ({ file: f, basename: path.basename(f), text: readFile(f) }))

// ── build scope (2026-07-23) ──────────────────────────────────────────────────────────────────
// This gate used to walk the WHOLE theme, unlike #3/#8/#9/#11/#16/#22 which all diff against the
// vendored base. On a Dawn repo that means ~100 vendor files every forbid-rule must not match, so a
// rule calibrated on our own sections fires on Shopify's. Measured before this fix, on a real client:
// an inline-<style> rule hit 6 stock Dawn sections and 1 real one; a numbered-settings rule hit 2 stock
// and 1 real. Precision worse than recall makes the whole "append a JSON line to enforce" surface
// unusable, so the pack silently stayed at 8 rules.
//
// Scope = files ADDED or MODIFIED vs BASE_REF. Modified matters: the team edits stock Dawn sections
// (image-banner, slideshow) and adds non-conforming code there, which basename filtering would miss.
// forbid-* rules judge OUR work → build scope. require-*/pin-* ask "does the theme have X anywhere"
// → whole theme, always. A rule opts out with "appliesTo": "all".
const BASE_REF = process.env.BASE_REF || 'base'
const SCAN_ALL = process.env.RULE_PACK_SCAN_ALL === '1'
const SCOPED_TYPES = new Set(['forbid-text', 'forbid-section-pattern', 'forbid-css-pattern'])

function buildScopedFiles() {
  if (SCAN_ALL) return { files: null, reason: 'RULE_PACK_SCAN_ALL=1 — whole theme' }
  try {
    execFileSync('git', ['rev-parse', '--verify', `${BASE_REF}^{commit}`], { cwd, stdio: ['ignore', 'pipe', 'pipe'] })
  } catch {
    return { files: null, reason: `base ref "${BASE_REF}" unresolvable — forbid-rules fell back to the whole theme` }
  }
  try {
    const out = execFileSync('git', ['diff', '--diff-filter=AM', '--name-only', `${BASE_REF}..HEAD`, '--', 'sections', 'snippets', 'layout', 'templates', 'assets'], { cwd, encoding: 'utf-8', stdio: ['ignore', 'pipe', 'pipe'] })
    const set = new Set(out.split('\n').map((s) => s.trim()).filter(Boolean))
    return { files: set, reason: null }
  } catch (e) {
    return { files: null, reason: `git diff failed (${e.message}) — forbid-rules fell back to the whole theme` }
  }
}

// A generated file holds the literals every other file binds to, so grepping it punishes doing the
// right thing (same carve-out as gate #3, matched on the generator's own header rather than a name).
const isGenerated = (text) => /GENERATED by [A-Za-z0-9_.-]+/i.test(text.slice(0, 400))

function scopeCorpus(corpus, inScope) {
  if (!inScope) return corpus
  const keep = (list) => (list || []).filter((f) => inScope.has(f.file) && !isGenerated(f.text))
  return { ...corpus, sections: keep(corpus.sections), templates: keep(corpus.templates), css: keep(corpus.css) }
}

// Load + merge the bundled team-default pack and the optional per-store pack. Each accepts either a
// bare JSON array of rules or { rules: [...] }. Returns { rules, malformed }.
function loadRules() {
  const out = []; let malformed = null
  for (const [label, file] of [['team-default', TEAM_DEFAULT], ['store', path.resolve(cwd, STORE_PACK)]]) {
    if (!fs.existsSync(file)) continue
    try {
      const json = JSON.parse(fs.readFileSync(file, 'utf-8'))
      const rules = Array.isArray(json) ? json : Array.isArray(json.rules) ? json.rules : null
      if (!rules) { malformed = `${label} pack is not a JSON array (or {rules:[]})`; continue }
      for (const r of rules) out.push({ ...r, source: r.source || label })
    } catch (e) { malformed = `${label} pack invalid JSON: ${e.message}` }
  }
  return { rules: out, malformed }
}

function main() {
  const { rules, malformed } = loadRules()
  if (malformed) {
    writeReport('rule-pack', 43, { cwd, pass: false, blockers: [{ id: 'rule-pack.malformed', page: STORE_PACK, detail: malformed, evidence: '' }], warnings: [], evidence: { reason: malformed }, duration_ms: Date.now() - t0 }, REPORT_DIR)
    console.log(`rule-pack: ENV-ERROR — ${malformed}`)
    process.exit(2)
  }
  if (rules.length === 0) {
    writeReport('rule-pack', 43, { cwd, pass: true, blockers: [], warnings: [{ id: 'rule-pack.empty', page: '(rule-pack)', detail: 'no rules defined yet — the pack grows from real caught defects via quality-loop', evidence: '' }], evidence: { rules: 0 }, duration_ms: Date.now() - t0 }, REPORT_DIR)
    console.log('rule-pack: PASS — 0 rules')
    process.exit(0)
  }
  // include layout/ (theme.liquid — viewport, <html lang>, meta, skip-link) + snippets/ so rules can
  // see the whole theme, not just sections. Many a11y/SEO patterns live in layout, not sections.
  const sections = toEntries([...walk('sections', ['.liquid']), ...walk('layout', ['.liquid']), ...walk('snippets', ['.liquid'])])
  const corpus = {
    sections,
    templates: toEntries(walk('templates', ['.json'])),
    // assets/*.css + inline <style> blocks inside sections (for forbid-css-pattern)
    css: [...toEntries(walk('assets', ['.css'])), ...sections.filter((s) => /<style[\s>]/i.test(s.text)).map((s) => ({ ...s, basename: `${s.basename}#style` }))],
    ds: (() => { try { return JSON.parse(readFile('docs/design/design-system.json')) } catch { return null } })(),
  }
  const { files: inScope, reason: scopeReason } = buildScopedFiles()
  const scoped = scopeCorpus(corpus, inScope)
  // Split by rule type rather than filtering once: a require-* rule asking "does the theme have a
  // skip-link anywhere" must see layout/theme.liquid even though nobody touched it since base.
  const buildRules = rules.filter((r) => SCOPED_TYPES.has(r.type) && r.appliesTo !== 'all')
  const fullRules = rules.filter((r) => !buildRules.includes(r))
  const a = evaluateRules(buildRules, scoped)
  const b = evaluateRules(fullRules, corpus)
  const blockers = [...a.blockers, ...b.blockers]
  const warnings = [...a.warnings, ...b.warnings]
  const enforced = a.enforced + b.enforced
  if (scopeReason) warnings.push({ id: 'rule-pack.scope-unresolved', page: '.', detail: `${scopeReason} — findings may include vendored theme files; tag the base commit \`base\` so forbid-rules judge only this build's work`, evidence: BASE_REF })

  const pass = blockers.length === 0
  const scannedCount = scoped.sections.length + scoped.templates.length + scoped.css.length
  writeReport('rule-pack', 43, {
    cwd,
    pass,
    blockers,
    warnings,
    evidence: {
      rules: enforced,
      team: fs.existsSync(TEAM_DEFAULT),
      store: fs.existsSync(path.resolve(cwd, STORE_PACK)),
      // #45 gate-integrity reads `scanned` — a pass with scanned:0 is a skip wearing a pass's clothes.
      scanned: scannedCount,
      scope: inScope ? 'build-diff' : 'whole-theme',
      baseRef: BASE_REF,
      filesInScope: inScope ? inScope.size : null,
      buildRules: buildRules.length,
      fullRules: fullRules.length,
    },
    duration_ms: Date.now() - t0,
  }, REPORT_DIR)
  console.log(`rule-pack: ${pass ? 'PASS' : 'BLOCK'} — ${enforced} rule(s) · ${blockers.length} blocker(s), ${warnings.length} warning(s) · scope=${inScope ? `build-diff (${scannedCount} file(s))` : 'whole-theme'}`)
  for (const b of blockers) console.log(`  BLOCK ${b.id}: ${b.detail}`)
  for (const w of warnings) console.log(`  warn  ${w.id}: ${w.detail}`)
  process.exit(pass ? 0 : 1)
}

try { main() } catch (e) {
  writeReport('rule-pack', 43, { cwd, pass: false, blockers: [{ id: 'rule-pack.crash', page: '(rule-pack)', detail: `unexpected failure: ${e.message}`, evidence: '' }], warnings: [], evidence: {}, duration_ms: Date.now() - t0 }, REPORT_DIR)
  console.error(`rule-pack: CRASH — ${e.message}`)
  process.exit(2)
}
