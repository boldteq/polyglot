#!/usr/bin/env node
// audit-ownership — does any gate blame the team for a file the team does not own?
//
// Third sibling of audit-unproven-guards ("has this blocker ever fired?") and audit-vacuous-pass
// ("does this green tick mean anything?"). This one asks: "whose fault is this finding?"
//
// It exists because the SAME defect shape was found six separate times in one week, each by accident:
//   · stock Dawn        — 2 edited lines pulled a 3612-line base.css into the drift scan   (CB-10)
//   · stock Dawn        — its type vocabulary counted toward OUR "store-wide variety"       (CB-11)
//   · generated files   — the brand cascade flagged for holding the hex literals it exists to hold (CB-9)
//   · merchant data     — `shopify://shop_images/x.png`, i.e. a merchant's own image pick, read as a
//                         hardcoded URL (44 of 45 findings)                                 (CB-9)
//   · vendored toolkit  — our own test fixture's fake private key flagged as the client's secret (CB-9)
//   · Liquid/CSS code   — `| times: 0.75` and `{% assign ratio = 0.65 %}` read as money      (CB-12)
// Every one is a FALSE BLOCK, and a false block is as damaging as a false pass because it teaches the
// team to wave the gate through.
//
// Method: build a theme where each ownership class holds a deliberately "dirty" file, run every static
// gate, and report which gates reported findings against a class that is not the team's code. OURS is
// the control — a gate that flags nothing there is broken, not polite.
//
// Advisory (exit 0 always), like its siblings: the classification is the deliverable.
//
// Usage: node audit-ownership.mjs [--json]

import fs from 'node:fs'
import os from 'node:os'
import path from 'node:path'
import { execFileSync } from 'node:child_process'
import { fileURLToPath } from 'node:url'
import { isMain } from './lib/is-main.mjs'

const HERE = path.dirname(fileURLToPath(import.meta.url))

// Gates legitimately allowed to report against a class. Each entry is a claim someone stands behind.
export const ALLOWED = new Map([
  // repo-hygiene's whole job is auditing repo-level files, vendored ones included
  ['repo-hygiene', new Set(['vendored', 'merchant-data'])],
  // theme-check lints the theme as Shopify sees it — merchant JSON templates are in its remit
  ['code-lint', new Set(['merchant-data'])],
  // legal-pages/consent read merchant data to decide whether required pages exist at all
  ['legal-pages', new Set(['merchant-data'])],
  ['consent', new Set(['merchant-data'])],
  ['analytics-wiring', new Set(['merchant-data'])],
  // brand-sync's whole remit IS the generated cascade: whether it exists, is wired into a layout, and
  // is in step with the contract. Reporting on it is the job.
  ['brand-sync', new Set(['generated'])],
  // a GENERATED asset nobody references is still dead weight the client ships — that is a real finding
  // about our wiring, not a complaint about the generator's output. (brand-sync says the same thing
  // via cascade.not-wired; the duplication is deliberate belt-and-braces.)
  ['dead-code', new Set(['generated'])],
])

export function classify(page, cwd) {
  const p = String(page || '').replace(`${cwd}/`, '')
  if (/^toolkit\//.test(p)) return 'vendored'
  if (/^(templates|config)\//.test(p)) return 'merchant-data'
  if (/design-system\.css$/.test(p)) return 'generated'
  if (/(^|\/)(base|component-|reset|theme)[\w-]*\.css$/.test(p)) return 'theme-base'
  if (/^(sections|snippets|assets|layout)\//.test(p)) return 'ours'
  return 'other'
}

// A theme in which every ownership class holds something a gate might object to.
export function buildFixtureTheme() {
  const d = fs.mkdtempSync(path.join(os.tmpdir(), 'ownership-'))
  const w = (rel, body) => { fs.mkdirSync(path.join(d, path.dirname(rel)), { recursive: true }); fs.writeFileSync(path.join(d, rel), body) }
  const DIRTY_CSS = '.x { font-size: 13px; padding: 9px; color: #C8102E; }\n'

  // THEME BASE — stock, and untouched after the baseline commit
  w('assets/base.css', `html { font-size: 62.5%; }\n${DIRTY_CSS}`)
  w('layout/theme.liquid', '<!doctype html><html lang="en"><head>{{ content_for_header }}</head><body>{{ content_for_layout }}</body></html>\n')
  w('docs/design/design-system.json', JSON.stringify({ typography: { allowed_px: [16, 32], rem_root_px: 10 }, spacing: { scale: [8, 16, 24] } }))

  const git = (...a) => execFileSync('git', a, { cwd: d, stdio: ['ignore', 'ignore', 'ignore'] })
  git('init', '-q', '.')
  git('add', '-A'); git('-c', 'user.email=a@b.c', '-c', 'user.name=t', 'commit', '-q', '-m', 'theme base')
  git('tag', 'base')

  // Everything below lands AFTER the baseline, so scope resolves and the gates actually look.
  w('assets/design-system.css', ['/* GENERATED by generate-design-system-css.mjs — do not edit by hand.', '   ds-hash:deadbeef */',
    ':root {', '  --ds-color-x: #C8102E;', '  --ds-size-13: 13px;', '  --ds-space-9: 9px;', '}', ''].join('\n'))
  w('templates/index.json', JSON.stringify({ sections: { hero: { type: 'ours', settings: { image: 'shopify://shop_images/pick.png', heading: 'A merchant wrote this' } } }, order: ['hero'] }, null, 2))
  w('config/settings_data.json', JSON.stringify({ current: { logo: 'shopify://shop_images/logo.png', color_scheme: 'scheme-1' } }, null, 2))
  w('toolkit/scripts/__fixtures__/secret-probe/run-tests.mjs', '// fixture data\nconst FAKE = "-----BEGIN RSA PRIVATE KEY-----\\nnotreal\\n-----END RSA PRIVATE KEY-----"\nexport default FAKE\n')
  // OURS — the control. A gate that reports NOTHING here is broken, not polite.
  w('sections/ours.liquid', '{% style %}\n.ours { font-size: 13px; padding: 9px; color: #C8102E; }\n{% endstyle %}\n<div class="ours">Hardcoded English here</div>\n{% schema %}{ "name": "Ours" }{% endschema %}\n')
  w('assets/section-ours.css', DIRTY_CSS)
  git('add', '-A'); git('-c', 'user.email=a@b.c', '-c', 'user.name=t', 'commit', '-q', '-m', 'work')
  return d
}

function main() {
  const asJson = process.argv.includes('--json')
  let manifest
  try { manifest = JSON.parse(execFileSync(process.execPath, [path.join(HERE, 'theme-gates.mjs'), '--list-json'], { encoding: 'utf-8' })) }
  catch (e) { console.error(`audit-ownership: could not read the gate manifest — ${e.message}`); process.exit(0) }

  const dir = buildFixtureTheme()
  const rows = []
  for (const g of manifest.filter((x) => x.kind === 'static')) {
    const runner = g.runner === 'node' ? process.execPath : g.runner
    try {
      execFileSync(runner, [path.join(HERE, g.script)], {
        cwd: dir, stdio: ['ignore', 'ignore', 'ignore'], timeout: 60_000,
        env: { ...process.env, REPORT_DIR: 'gate-reports', BASE_REF: 'base' },
      })
    } catch { /* a non-zero exit is a verdict */ }
    let rep = null
    try { rep = JSON.parse(fs.readFileSync(path.join(dir, 'gate-reports', `${g.name}.json`), 'utf-8')) } catch { continue }
    const seen = new Map()
    for (const f of [...(rep.blockers || []), ...(rep.warnings || [])]) {
      const cls = classify(f.page, dir)
      if (cls === 'other') continue
      if (!seen.has(cls)) seen.set(cls, new Set())
      seen.get(cls).add(f.id)
    }
    for (const [cls, ids] of seen) rows.push({ gate: g.name, cls, ids: [...ids] })
  }
  fs.rmSync(dir, { recursive: true, force: true })

  const misattributed = rows.filter((r) => r.cls !== 'ours' && !(ALLOWED.get(r.gate)?.has(r.cls)))
  const controls = new Set(rows.filter((r) => r.cls === 'ours').map((r) => r.gate))

  if (asJson) { console.log(JSON.stringify({ rows, misattributed, controls: [...controls] }, null, 2)); process.exit(0) }

  console.log(`audit-ownership: static gates run against a theme where every ownership class is "dirty"\n`)
  console.log(`  ${controls.size} gate(s) flagged OUR code (the control — these are working)`)
  if (!misattributed.length) {
    console.log('\n✅ no gate reported a finding against theme-base, generated, merchant-data or vendored files.')
    process.exit(0)
  }
  console.log(`\n⚠️  ${misattributed.length} gate/class pair(s) reported against code the team does not own:`)
  for (const r of misattributed) console.log(`   ${r.gate.padEnd(20)} → ${r.cls.padEnd(14)} ${r.ids.slice(0, 3).join(', ')}`)
  console.log('\nEach needs a call: is the gate right to look there (add it to ALLOWED with the reason),')
  console.log('or is this the false-attribution class again? A false BLOCK is as damaging as a false pass —')
  console.log('it teaches the team to wave the gate through.')
  process.exit(0)
}

if (isMain(import.meta.url)) main()
