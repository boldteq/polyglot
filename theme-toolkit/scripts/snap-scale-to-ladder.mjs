#!/usr/bin/env node
// snap-scale-to-ladder — move off-scale font-size / spacing values onto the ratified ladder.
//
// The CB-3 companion to snap-colors-to-tokens. That tool could be fully mechanical because its rule is
// IDENTITY: a literal is swapped only when it already equals a token, so the render cannot change.
// Type and spacing have no such luxury — snapping 15px to 16px CHANGES WHAT RENDERS. So this tool is
// built the other way round: it is a REPORTER first, and applying is gated.
//
// THE RULE: a snap is mechanical only while it is imperceptible. Every change carries its delta, and
// --apply REFUSES when any snap exceeds --max-delta (default 2px). A larger jump is a design decision —
// which size did they mean? — and guessing it silently is the documented anti-pattern this whole
// workstream exists to stop (cravinbyandy: 15px appears 18 times; moving it is a visible change to most
// body copy on the site).
//
//   node toolkit/scripts/snap-scale-to-ladder.mjs                  # dry run: every change + its delta
//   node toolkit/scripts/snap-scale-to-ladder.mjs --apply          # write (refuses above --max-delta)
//   node toolkit/scripts/snap-scale-to-ladder.mjs --max-delta 4    # widen the bar, deliberately
//   node toolkit/scripts/snap-scale-to-ladder.mjs --only assets/section-hero.css
//
// Scope mirrors check-design-system: assets/*.css + sections|snippets/*.liquid style blocks, never a
// GENERATED file, never positioning props, never a number inside calc()/min()/max()/clamp() — those are
// formula constants, and snapping one changes geometry rather than rhythm (CB-2).
//
// Env: DESIGN_SYSTEM (docs/design/design-system.json)
// Exit: 0 ok · 1 refused (a snap exceeds the bar, with --apply) · 2 env error

import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const cwd = process.cwd()
const DS = process.env.DESIGN_SYSTEM || 'docs/design/design-system.json'

// Properties that carry RHYTHM. Positioning (top/right/bottom/left/inset) is geometry, not rhythm.
const SPACE_PROP = /^(margin|padding)(-(top|right|bottom|left))?$|^(gap|row-gap|column-gap)$/
const FORMULA = /\b(calc|min|max|clamp)\(/i

export function nearest(value, ladder) {
  if (!ladder.length) return null
  let best = ladder[0]
  for (const step of ladder) if (Math.abs(step - value) < Math.abs(best - value)) best = step
  return best
}

// Returns { text, changes: [{prop, from, to, delta, line}], skipped: [{prop, value, why}] }
export function snapCss(src, { type = [], space = [] }, remRoot = 16) {
  const changes = []
  const skipped = []
  const text = String(src).replace(/([a-zA-Z-]+)\s*:\s*([^;{}]+)(?=[;}])/g, (whole, rawProp, rawVal, offset) => {
    const prop = rawProp.toLowerCase()
    const value = rawVal
    const isType = prop === 'font-size'
    const isSpace = SPACE_PROP.test(prop)
    if (!isType && !isSpace) return whole
    if (/var\(/.test(value)) return whole                       // already bound to a token
    if (FORMULA.test(value)) { skipped.push({ prop, value: value.trim(), why: 'formula constant (calc/clamp) — snapping changes geometry' }); return whole }
    const ladder = isType ? type : space
    if (!ladder.length) return whole

    const line = String(src).slice(0, offset).split('\n').length
    let touched = false
    const newVal = value.replace(/(-?\d*\.?\d+)(px|rem)\b/g, (numWhole, num, unit) => {
      const px = unit === 'rem' ? Number(num) * remRoot : Number(num)
      if (!Number.isFinite(px) || px === 0) return numWhole
      if (ladder.includes(px)) return numWhole                  // already on the ladder
      const to = nearest(Math.abs(px), ladder)
      if (to === null) return numWhole
      const delta = Math.abs(Math.abs(px) - to)
      const signed = px < 0 ? -to : to
      changes.push({ prop, from: px, to: signed, delta, line })
      touched = true
      return unit === 'rem' ? `${signed / remRoot}rem` : `${signed}px`
    })
    return touched ? whole.replace(value, newVal) : whole
  })
  return { text, changes, skipped }
}

// Only the INSIDE of a {% style %} / {% stylesheet %} block is CSS; the rest of a .liquid is markup.
export function snapLiquid(src, ladders, remRoot) {
  const BLOCK = /(\{%-?\s*(?:style|stylesheet)[^%]*-?%\})([\s\S]*?)(\{%-?\s*end(?:style|stylesheet)\s*-?%\})/g
  let changes = []
  let skipped = []
  const text = String(src).replace(BLOCK, (whole, open, body, close) => {
    const r = snapCss(body, ladders, remRoot)
    changes = changes.concat(r.changes); skipped = skipped.concat(r.skipped)
    return open + r.text + close
  })
  return { text, changes, skipped }
}

const isGenerated = (t) => /GENERATED by [\w.-]+/i.test(String(t).slice(0, 400))

function detectRemRootPx(contract) {
  const declared = Number(contract?.typography?.rem_root_px)
  if (declared > 0) return declared
  for (const f of ['assets/base.css', 'assets/reset.css', 'assets/theme.css', 'assets/section-password.css', 'assets/template-giftcard.css', 'assets/premium.css']) {
    try {
      const p = path.resolve(cwd, f)
      if (fs.existsSync(p) && /font-size:\s*(?:calc\([^;{}]*?)?62\.5%/.test(fs.readFileSync(p, 'utf-8'))) return 10
    } catch { /* next */ }
  }
  return 16
}

function die(msg) { console.error(`snap-scale: ENV-ERROR — ${msg}`); process.exit(2) }

function main() {
  const argv = process.argv.slice(2)
  const apply = argv.includes('--apply')
  const only = argv.includes('--only') ? argv[argv.indexOf('--only') + 1] : null
  const maxDelta = argv.includes('--max-delta') ? Number(argv[argv.indexOf('--max-delta') + 1]) : 2

  let contract
  try { contract = JSON.parse(fs.readFileSync(path.resolve(cwd, DS), 'utf-8').replace(/\/\*[\s\S]*?\*\//g, '')) }
  catch (e) { die(`cannot read ${DS}: ${e.message}`) }
  const type = (contract.typography?.allowed_px || []).map(Number).filter(Number.isFinite)
  const space = (contract.spacing?.scale || []).map(Number).filter(Number.isFinite)
  if (!type.length && !space.length) die(`${DS} defines neither typography.allowed_px nor spacing.scale — nothing to snap onto`)
  // rem ROOT: Dawn-based themes reset html to 62.5% (1rem = 10px) and author against THAT root.
  // Assuming 16 inflates every rem by 1.6x and manufactures phantom drift — the first dry run against
  // cravinbyandy produced 754 "off-ladder" values that were all rem x 1.6 (19.2 / 9.6 / 22.4 / 51.2).
  // Same detection as check-design-system.detectRemRootPx, and for the same reason.
  const remRoot = detectRemRootPx(contract)

  const targets = []
  for (const dir of ['assets', 'sections', 'snippets']) {
    let names = []
    try { names = fs.readdirSync(path.resolve(cwd, dir)) } catch { continue }
    for (const n of names) {
      if (!/\.(css|liquid)$/.test(n)) continue
      const rel = path.join(dir, n)
      if (only && rel !== only && n !== only) continue
      targets.push(rel)
    }
  }

  let all = []
  let skippedAll = []
  const pending = []
  for (const rel of targets) {
    const abs = path.resolve(cwd, rel)
    const src = fs.readFileSync(abs, 'utf-8')
    if (isGenerated(src)) continue
    const r = /\.liquid$/.test(rel) ? snapLiquid(src, { type, space }, remRoot) : snapCss(src, { type, space }, remRoot)
    if (!r.changes.length) { skippedAll = skippedAll.concat(r.skipped); continue }
    all = all.concat(r.changes.map((c) => ({ ...c, file: rel })))
    skippedAll = skippedAll.concat(r.skipped)
    pending.push({ abs, text: r.text, rel, n: r.changes.length })
  }

  if (!all.length) {
    console.log(`snap-scale: nothing to snap — every font-size/spacing value is already on the ladder (type [${type.join(', ')}] · spacing [${space.join(', ')}])`)
    process.exit(0)
  }

  const over = all.filter((c) => c.delta > maxDelta)
  const byFile = new Map()
  for (const c of all) byFile.set(c.file, (byFile.get(c.file) || 0) + 1)
  for (const [f, n] of [...byFile.entries()].sort((a, b) => b[1] - a[1])) console.log(`${apply && !over.length ? 'snapped' : 'would snap'} ${String(n).padStart(3)} in ${f}`)

  const worst = all.reduce((m, c) => Math.max(m, c.delta), 0)
  console.log(`\nsnap-scale: ${all.length} value(s) off the ladder · largest move ${worst}px · bar ${maxDelta}px`)
  const buckets = new Map()
  for (const c of all) { const k = `${c.from}→${c.to}`; buckets.set(k, (buckets.get(k) || 0) + 1) }
  console.log('\nmoves (how many, and by how much):')
  for (const [k, n] of [...buckets.entries()].sort((a, b) => b[1] - a[1]).slice(0, 14)) {
    const [from, to] = k.split('→').map(Number)
    console.log(`  ${String(n).padStart(3)}×  ${k}px  (${Math.abs(from - to)}px)`)
  }
  if (skippedAll.length) console.log(`\n${skippedAll.length} value(s) left alone (formula constants — snapping one changes geometry, not rhythm)`)

  if (!apply) { console.log('\nre-run with --apply to write. Nothing above the bar may be applied without raising --max-delta deliberately.'); process.exit(0) }
  if (over.length) {
    console.error(`\nREFUSED — ${over.length} snap(s) move more than ${maxDelta}px, the largest ${worst}px.`)
    console.error('A move that size is a DESIGN decision (which size did they mean?), not a mechanical one.')
    console.error('Either tighten the ladder, or raise the bar deliberately: --max-delta <px>.')
    for (const c of over.slice(0, 6)) console.error(`  ${c.file}:${c.line} ${c.prop} ${c.from} → ${c.to} (${c.delta}px)`)
    process.exit(1)
  }
  for (const p of pending) fs.writeFileSync(p.abs, p.text)
  console.log(`\napplied to ${pending.length} file(s) — every move ≤ ${maxDelta}px`)
  process.exit(0)
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) main()
